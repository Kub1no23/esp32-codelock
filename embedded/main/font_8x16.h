#define FONT_KEYPAD_GLYPHS_COUNT (sizeof(font_keypad_glyphs) / sizeof(font_glyph_t))

static inline const uint8_t *font_get_glyph(char c)
{
    for (size_t i = 0; i < FONT_KEYPAD_GLYPHS_COUNT; i++)
    {
        if (font_keypad_glyphs[i].c == c)
        {
            return font_keypad_glyphs[i].bitmap;
        }
    }

    return font_keypad_glyphs[0].bitmap;
}

